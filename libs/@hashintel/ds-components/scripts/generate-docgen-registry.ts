/**
 * Generates `docs/blocks/props-table/docgen-registry.gen.ts`: an
 * identity-keyed map from the library's exported components to their
 * react-docgen-typescript prop docs. Storybook's docgen plugin attaches the
 * same data to `Component.__docgenInfo` while bundling; the registry stands in
 * for it in the published `dist/docs` modules, where no such bundler runs.
 */
import { globSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import ts from "@typescript/typescript6";
import { withCompilerOptions } from "react-docgen-typescript";

import { docgenParserOptions } from "../docs/docgen-options";

import type { ComponentDoc, PropItem } from "react-docgen-typescript";

const outFile = "docs/blocks/props-table/docgen-registry.gen.ts";

const sourceFiles = [
  ...globSync("./src/components/*/*.tsx", {
    exclude: ["**/*.stories.tsx", "**/*.test.tsx"],
  }),
  // Compound parts (Dialog.Body, Popover.Footer, …) are defined in src/util.
  ...globSync("./src/util/**/*.tsx", {
    exclude: ["**/*.stories.tsx", "**/*.test.tsx", "**/*.fixtures.tsx"],
  }),
].sort();

const parsedConfig = ts.getParsedCommandLineOfConfigFile(
  path.resolve("tsconfig.json"),
  {},
  {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (diagnostic) => {
      throw new Error(
        ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n"),
      );
    },
  },
);
if (!parsedConfig) {
  throw new Error("Failed to parse tsconfig.json");
}

const program = ts.createProgram(
  sourceFiles.map((file) => path.resolve(file)),
  parsedConfig.options,
);

const componentDocs = withCompilerOptions(
  parsedConfig.options,
  docgenParserOptions,
).parseWithProgramProvider(sourceFiles, () => program);

// Docgen also documents non-exported components (internal helpers referenced
// from exported types); the registry can only reference value exports.
const checker = program.getTypeChecker();
const valueExportsByFile = new Map<string, Set<string>>();
for (const file of sourceFiles) {
  const sourceFile = program.getSourceFile(path.resolve(file));
  const moduleSymbol = sourceFile && checker.getSymbolAtLocation(sourceFile);
  const names = new Set<string>();
  for (const symbol of moduleSymbol
    ? checker.getExportsOfModule(moduleSymbol)
    : []) {
    const resolved =
      symbol.flags & ts.SymbolFlags.Alias
        ? checker.getAliasedSymbol(symbol)
        : symbol;
    if (resolved.flags & ts.SymbolFlags.Value) {
      names.add(symbol.getName());
    }
  }
  valueExportsByFile.set(
    path.relative(process.cwd(), path.resolve(file)).replaceAll("\\", "/"),
    names,
  );
}

// The registry keys are the live export objects, so only docs whose name is a
// valid identifier (i.e. an actual named export) can be referenced. Docgen
// reports some files relative and some absolute; normalize so each module is
// imported once.
const docsByFile = new Map<string, Map<string, ComponentDoc>>();
for (const doc of componentDocs) {
  if (!/^[A-Za-z_$][\w$]*$/.test(doc.displayName)) {
    continue;
  }
  const filePath = path
    .relative(process.cwd(), path.resolve(doc.filePath))
    .replaceAll("\\", "/");
  if (!valueExportsByFile.get(filePath)?.has(doc.displayName)) {
    continue;
  }
  const fileDocs = docsByFile.get(filePath) ?? new Map<string, ComponentDoc>();
  fileDocs.set(doc.displayName, doc);
  docsByFile.set(filePath, fileDocs);
}

// parent/declarations only exist to drive propFilter and carry source paths
// the published data has no use for.
const stripProp = ({
  parent: _parent,
  declarations: _declarations,
  ...rest
}: PropItem) => rest;

const imports: string[] = [];
const entries: string[] = [];
for (const [filePath, fileDocs] of [...docsByFile.entries()].sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const moduleVar = `m${imports.length}`;
  imports.push(
    `import * as ${moduleVar} from "../../../${filePath.replace(/\.tsx$/, "")}";`,
  );
  for (const [exportName, doc] of fileDocs) {
    const props = Object.fromEntries(
      Object.entries(doc.props).map(([propName, prop]) => [
        propName,
        stripProp(prop),
      ]),
    );
    entries.push(
      `  [${moduleVar}.${exportName}, { props: ${JSON.stringify(props)} }],`,
    );
  }
}

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `/**
 * Generated by \`scripts/generate-docgen-registry.ts\` — do not edit.
 *
 * Identity-keyed react-docgen-typescript prop docs for every exported
 * component, consumed by \`PropsTable\` when Storybook's bundler hasn't
 * attached \`__docgenInfo\`.
 */
import type { ComponentDoc } from "react-docgen-typescript";

${imports.join("\n")}

export type DocgenRegistryInfo = Pick<ComponentDoc, "props">;

export const docgenRegistry: ReadonlyMap<unknown, DocgenRegistryInfo> = new Map<
  unknown,
  DocgenRegistryInfo
>([
${entries.join("\n")}
]);
`,
);

console.log(`Wrote ${entries.length} component docs to ${outFile}`);
