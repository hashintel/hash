import { describe, expect, it } from "vitest";

import {
  emitReactiveModuleFiles,
  emitReactiveModulePython,
  moduleFileStem,
} from "./emit-reactive-module-python";
import {
  binary,
  bool,
  ite,
  not,
  num,
  ref,
  relu,
  scale,
} from "./reactive-module-graph";

import type { ReactiveModuleGraph } from "./reactive-module-graph";

const graph: ReactiveModuleGraph = {
  header: "ops: generated by Petrinaut. Do not edit.",
  variables: [
    { name: "Level", sort: "real", role: "place" },
    { name: "Full", sort: "bool", role: "flag" },
  ],
  modules: [
    {
      className: "Ops",
      instance: "ops",
      docstring: "Every operator the graph has.",
      theory: "LRA",
      ctrl: ["Level", "Full"],
      extl: [],
      init: [num(0), bool(false)],
      update: [],
      returns: [
        // 0.5 * (Level - 1) + relu(2 - Level), the max form
        binary(
          "+",
          scale(0.5, binary("-", ref("Level"), num(1))),
          relu(binary("-", num(2), ref("Level"))),
        ),
        // ~(Level < 3) | ((ite(Full, 4, 0) == 4) & Full), a literal-only ite inside
        binary(
          "|",
          not(binary("<", ref("Level"), num(3))),
          binary(
            "&",
            binary("==", ite(ref("Full"), num(4), num(0)), num(4)),
            ref("Full"),
          ),
        ),
      ],
    },
  ],
  root: { kind: "single", module: "ops" },
};

describe("emitReactiveModulePython", () => {
  it("renders comparisons, logic, scaling, relu and literal branches under Python's precedence", () => {
    expect(emitReactiveModulePython(graph)).toBe(
      `"""ops: generated by Petrinaut. Do not edit."""

from zrth import LRA, Bool, Real, Var, expr
from zrth.expr import relu
from zrth.sugar import Module, ite

REAL = Real([1, 1])
BOOL = Bool([1, 1])

Level = Var(REAL)

Full = Var(BOOL)


class Ops(Module):
    """Every operator the graph has."""

    def init(self):
        return 0.0, False

    def update(self, Level, Full):
        return 0.5 * (Level - 1.0) + relu(2.0 - Level), ~(Level < 3.0) | ((ite(Full, expr(4.0, theory=LRA, sort=REAL), 0.0) == 4.0) & Full)


net = Ops(theory=LRA, ctrl=(Level, Full))
`,
    );
  });
});

describe("emitReactiveModulePython with the next syntax", () => {
  it("names the step method next in every file", () => {
    expect(emitReactiveModulePython(graph, { syntax: "next" })).toContain(
      "    def next(self, Level, Full):",
    );
    expect(emitReactiveModulePython(graph)).toContain(
      "    def update(self, Level, Full):",
    );
    const [, ops] = emitReactiveModuleFiles(graph, { syntax: "next" });
    expect(ops?.text).toContain("    def next(self, Level, Full):");
    expect(ops?.text).not.toContain("def update(");
  });
});

describe("emitReactiveModuleFiles", () => {
  it("names a module's file after its class", () => {
    expect(moduleFileStem("Transition_Infection")).toBe("transition_infection");
    expect(moduleFileStem("Place_FooBar2")).toBe("place_foo_bar2");
    expect(moduleFileStem("Draw_ABTest")).toBe("draw_ab_test");
  });

  it("numbers the stem of a module whose class name folds onto an earlier one", () => {
    const twin = (className: string, instance: string) => ({
      ...graph.modules[0]!,
      className,
      instance,
    });
    const files = emitReactiveModuleFiles({
      ...graph,
      modules: [
        twin("Place_Ab", "a"),
        twin("Place_AB", "b"),
        twin("Place_ab", "c"),
      ],
      root: { kind: "compose", modules: ["a", "b", "c"] },
    });
    expect(files.map((file) => file.path)).toEqual([
      "net.py",
      "place_ab.py",
      "place_ab_2.py",
      "place_ab_3.py",
    ]);
    expect(files[0]?.text).toContain("from place_ab_2 import Place_AB");
    expect(files[2]?.text).toContain("class Place_AB(Module):");
  });

  it("writes net.py first and gives a module the imports and sorts its own body needs", () => {
    const files = emitReactiveModuleFiles(graph);
    expect(files.map((file) => file.path)).toEqual(["net.py", "ops.py"]);
    expect(files[0]?.text).toBe(
      `"""ops: generated by Petrinaut. Do not edit."""

from zrth import LRA, Bool, Real, Var

from ops import Ops

REAL = Real([1, 1])
BOOL = Bool([1, 1])

Level = Var(REAL)

Full = Var(BOOL)


net = Ops(theory=LRA, ctrl=(Level, Full))
`,
    );
    const [, ops] = files;
    expect(
      ops?.text.startsWith(`"""ops: generated by Petrinaut. Do not edit."""

from zrth import LRA, Real, expr
from zrth.expr import relu
from zrth.sugar import Module, ite

REAL = Real([1, 1])


class Ops(Module):
`),
    ).toBe(true);
    expect(ops?.text).toContain("expr(4.0, theory=LRA, sort=REAL)");
  });
});
