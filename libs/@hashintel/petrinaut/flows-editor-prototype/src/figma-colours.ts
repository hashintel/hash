/**
 * The colour token layer from the Figma DS (file WmnosvOvi4Blw0HK0jh1mG), the source of truth that `ds-components`
 * has not caught up with (Aakarsh, 4 Nov). In code the alpha steps are far lighter and the semantic tokens point at
 * alpha steps; in Figma the neutral backgrounds are solid steps (`neutral.bg.surface.active` is a20 #00000006 in
 * code, s30 #f0f0f0 in Figma) and the borders are black alpha steps.
 *
 * The layer keeps the code's token names, so no component changes: it rewrites every `--colors-*` core step to its
 * Figma value and points every semantic token at the core step Figma uses (`figma-colour-values.ts`, generated by
 * `scripts/gen-figma-colours.py`). Panda's semantic tokens are `var()` references, so palette classes and the Flows
 * palettes (`status-colors.ts`) pick the new values up too.
 *
 * Names that differ: Figma's text set is heading, body, subtle; the code's is heading, body, muted, subtle. `muted`
 * takes Figma's "subtle - hover" step (between body and subtle), `muted.hover` takes body. Pink has no Figma
 * semantic set and keeps the code's. `bgSolid.*` keeps the code's structure on Figma's core steps.
 *
 * Compare: ?ds=code shows `ds-components` as it is; ?ds=figma (the default) this layer. Remembered in localStorage.
 */
import { figmaCore, figmaSemantic } from "./figma-colour-values";

export type DsColours = "figma" | "code";

const storageKey = "flows-proto:ds:v1";

const isDsColours = (value: string | null): value is DsColours =>
  value === "figma" || value === "code";

/** Three ids beat the DS preset's two (`.petrinaut-root:not(#\#):not(#\#)`), so the layer wins without !important. */
const selector = ".petrinaut-root:not(#\\#):not(#\\#):not(#\\#)";

/** The code-only solid surface takes Figma's surface hover and active steps too (s20, s30). */
const solidSurface: Record<string, string> = {
  "--colors-neutral-bg-solid-surface-hover": "var(--colors-neutral-s20)",
  "--colors-neutral-bg-solid-surface-active": "var(--colors-neutral-s30)",
};

/**
 * The DS Button's subtle variant borders on core steps (`neutral.a60`, hover `neutral.a80`), not on `neutral.bd.*`.
 * Figma's alpha steps are far darker than the code's (a60 is 40% black, the code's is 15%), so on the layer the border
 * went dark. Figma's Button (outline, neutral) strokes with `neutral/bd/solid` (a30, 15%) and hovers to
 * `neutral/bd/solid/hover` (a40, 20%), so inside those buttons the two steps point there.
 */
const buttonBorders = `button[class~="bd-c_neutral.a60"] { --colors-neutral-a60: var(--colors-neutral-bd-solid); --colors-neutral-a80: var(--colors-neutral-bd-solid-hover); }`;

/**
 * ?hover=s20|s25|s30|s35 sets every neutral hover background to that solid step, to compare darker hovers live
 * (Aakarsh, 4 Nov). Without it, each hover is Figma's own step (s20 for surface, subtle and min; s25 for shaded).
 */
const hoverSteps = ["s20", "s25", "s30", "s35"] as const;
type HoverStep = (typeof hoverSteps)[number];
const isHoverStep = (value: string | null): value is HoverStep =>
  hoverSteps.some((step) => step === value);

const hoverTokens = ["min", "surface", "subtle", "shaded"].flatMap((level) => [
  `--colors-neutral-bg-${level}-hover`,
  `--colors-neutral-bg-solid-${level}-hover`,
]);

const hoverOverride = (): Record<string, string> => {
  const step = new URLSearchParams(globalThis.location.search).get("hover");
  return isHoverStep(step)
    ? Object.fromEntries(
        hoverTokens.map((name) => [name, `var(--colors-neutral-${step})`]),
      )
    : {};
};

export const applyDsColours = (mode: DsColours) => {
  const { document } = globalThis;
  let sheet = document.getElementById("flows-ds-colours");
  if (!sheet) {
    sheet = document.createElement("style");
    sheet.id = "flows-ds-colours";
    document.head.append(sheet);
  }
  const declarations = Object.entries({
    ...figmaCore,
    ...figmaSemantic,
    ...solidSurface,
    ...hoverOverride(),
  })
    .map(([name, value]) => `${name}: ${value};`)
    .join(" ");
  sheet.textContent =
    mode === "figma"
      ? `${selector} { ${declarations} } ${selector} ${buttonBorders}`
      : "";
  document.documentElement.dataset.dsColours = mode;
  try {
    globalThis.localStorage.setItem(storageKey, mode);
  } catch {
    // Blocked storage: the pick lasts for this page.
  }
};

/** At start: ?ds= wins, then the remembered pick, then Figma. */
export const initDsColours = () => {
  const fromQuery = new URLSearchParams(globalThis.location.search).get("ds");
  let stored: string | null = null;
  try {
    stored = globalThis.localStorage.getItem(storageKey);
  } catch {
    // Blocked storage.
  }
  applyDsColours(
    isDsColours(fromQuery) ? fromQuery : isDsColours(stored) ? stored : "figma",
  );
};
