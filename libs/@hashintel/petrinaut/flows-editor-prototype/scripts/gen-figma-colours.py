"""Writes src/figma-colour-values.ts from the Figma DS colour export (ops/projects/flows-editor/references/ds-colour-tokens-1104.json).

Usage: python3 scripts/gen-figma-colours.py <path to ds-colour-tokens json>
"""
import json
import sys

source = json.load(open(sys.argv[1]))
core, semantic = source["color.core"], source["color.semantic"]


def core_var(alias):
    parts = alias.split("/")
    if parts[0] == "Static":
        name = parts[1]
        return f"--colors-{name}" if parts[2] == "solid" else f"--colors-{name}-{parts[3]}"
    return f"--colors-{parts[0].lower()}-{parts[2]}"


variables = {}
for alias, entry in core.items():
    variables[core_var(alias)] = entry["hex"]

STATES = {"default": "", "hover": "-hover", "active": "-active", "disabled": "-disabled", "disbaled": "-disabled"}
FG = {
    "text/max": "fg-max",
    "text/solid": "fg-on-solid",
    "text/heading": "fg-heading",
    "text/body": "fg-body",
    "text/body-hover": "fg-body-hover",
    "text/subtle - hover": "fg-muted",
    "text/muted - disabled": ["fg-body-disabled", "fg-muted-disabled", "fg-subtle-disabled", "fg-link-disabled"],
    "text/subtle": "fg-subtle",
    "text/link": ["fg-link", "fg-link-active"],
    "text/link-hover": "fg-link-hover",
}
semantic_vars = {}
for key, entry in semantic.items():
    palette, group, *rest = key.split("/")
    reference = f"var({core_var(entry['alias'])})"
    if group in ("bg", "bd") and len(rest) == 2 and rest[1] in STATES:
        semantic_vars[f"--colors-{palette}-{group}-{rest[0]}{STATES[rest[1]]}"] = reference
    elif group == "fg" and "/".join(rest) in FG:
        targets = FG["/".join(rest)]
        for target in targets if isinstance(targets, list) else [targets]:
            semantic_vars[f"--colors-{palette}-{target}"] = reference
# Hovers the Figma text set has no exact name for: muted hovers to body, subtle hovers to Figma's "subtle - hover".
for palette in {key.split("/")[0] for key in semantic}:
    semantic_vars[f"--colors-{palette}-fg-muted-hover"] = semantic_vars[f"--colors-{palette}-fg-body"]
    semantic_vars[f"--colors-{palette}-fg-subtle-hover"] = semantic_vars[f"--colors-{palette}-fg-muted"]

lines = [
    "// Generated by scripts/gen-figma-colours.py from the Figma DS (file WmnosvOvi4Blw0HK0jh1mG, read 4 Nov 2026). Do not edit.",
    "",
    "/** Core steps: every solid and alpha step, as Figma has it. */",
    "export const figmaCore: Record<string, string> = {",
    *[f'  "{name}": "{value}",' for name, value in sorted(variables.items())],
    "};",
    "",
    "/** Semantic tokens under the code's names, each pointing at the core step Figma uses. */",
    "export const figmaSemantic: Record<string, string> = {",
    *[f'  "{name}": "{value}",' for name, value in sorted(semantic_vars.items())],
    "};",
    "",
]
open("src/figma-colour-values.ts", "w").write("\n".join(lines))
print(len(variables), "core,", len(semantic_vars), "semantic")
