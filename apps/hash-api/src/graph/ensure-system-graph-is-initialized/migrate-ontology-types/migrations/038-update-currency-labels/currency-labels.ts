export const getCurrencyLabel = (code: string): ValueLabel => {
  const symbol = currencySymbols[code];

  return {
    ...(symbol
      ? { left: /[\p{L}.]$/u.test(symbol) ? `${symbol}\u00a0` : symbol }
      : {}),
    right: code,
  };
};
